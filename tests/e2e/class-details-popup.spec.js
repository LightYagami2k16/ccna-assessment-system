import { expect, test } from '@playwright/test'

for (const role of ['instructor', 'administrator']) {
  test(`${role} class cards open details with roster and protected management actions`, async ({ page }, testInfo) => {
    const classSection = { id: 'class-one', name: 'Networks Section A', code: 'ITN-A', academicTerm: '2026 semester 1', isActive: true, joinCode: 'ABCDEFGH', studentIds: ['student-one'], teacherName: 'Sample Teacher', teacherEmail: 'teacher@example.test' }
    await page.route('**/rest/v1/**', (route) => {
      const endpoint = new URL(route.request().url()).pathname.split('/').at(-1)
      return route.fulfill({ json: endpoint === 'get_assignment_workspace' ? { classes: [classSection], students: [{ id: 'student-one', fullName: 'Ada Student', email: 'ada@example.test' }], quizzes: [], approvalRequests: [] } : [] })
    })
    await page.setViewportSize({ width: role === 'instructor' ? 390 : 1440, height: 1000 })
    const path = role === 'instructor' ? '/instructor/classes' : '/admin/assessment-tools/classes'
    await page.goto(`/?uat-role=${role}#${path}`)
    const card = page.locator('.class-card')
    await expect(card).toBeVisible({ timeout: 45000 })
    await expect(card.getByRole('button')).toHaveCount(1)
    await expect(card.getByRole('checkbox')).toHaveCount(0)
    await expect(card.getByText('2026 semester 1', { exact: true })).toHaveCount(0)
    await card.getByRole('button', { name: 'Show details', exact: true }).click()
    const popup = page.getByRole('dialog', { name: classSection.name, exact: true })
    await expect(popup.getByText('CLASS DETAILS', { exact: true })).toBeVisible()
    await expect(popup.getByText('ITN-A', { exact: true })).toBeVisible()
    await expect(popup.getByText('ABCDEFGH', { exact: true })).toBeVisible()
    if (role === 'administrator') await expect(popup.getByText('Sample Teacher', { exact: true })).toBeVisible()
    await popup.getByRole('checkbox', { name: 'Select for deletion', exact: true }).check()
    await popup.getByRole('button', { name: 'Show students', exact: true }).click()
    await expect(popup.getByText('Ada Student', { exact: true })).toBeVisible()
    await popup.getByRole('button', { name: 'Reset password', exact: true }).click()
    await page.getByRole('dialog', { name: 'Reset student password?', exact: true }).getByRole('button', { name: 'Cancel', exact: true }).click()
    await popup.getByRole('button', { name: 'New code', exact: true }).click()
    const confirmation = page.getByRole('dialog', { name: 'Generate a new class code?', exact: true })
    await expect(confirmation).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(confirmation).not.toBeVisible()
    await expect(popup).toBeVisible()
    await expect(popup.getByRole('button', { name: 'New code', exact: true })).toBeFocused()
    await popup.getByRole('button', { name: 'Show QR code', exact: true }).click()
    await expect(popup.getByRole('img', { name: `QR code for joining ${classSection.name}` })).toBeVisible()
    await popup.getByRole('button', { name: 'Hide QR code', exact: true }).click()
    await popup.getByRole('button', { name: 'Delete', exact: true }).click()
    await page.getByRole('dialog', { name: 'Delete class?', exact: true }).getByRole('button', { name: 'Cancel', exact: true }).click()
    await popup.getByRole('button', { name: 'Close details', exact: true }).focus()
    await page.keyboard.press('Shift+Tab')
    await expect(popup.getByRole('button', { name: 'Done', exact: true })).toBeFocused()
    await popup.evaluate((element) => { element.scrollTop = 0 })
    await page.screenshot({ path: testInfo.outputPath('class-details.png') })
    await page.keyboard.press('Escape')
    await expect(popup).not.toBeVisible()
    await expect(card.getByRole('button', { name: 'Show details', exact: true })).toBeFocused()
    await card.getByRole('button', { name: 'Show details', exact: true }).click()
    await expect(popup.getByRole('checkbox', { name: 'Select for deletion', exact: true })).toBeChecked()
    await popup.getByRole('button', { name: 'Edit class', exact: true }).click()
    await expect(popup).not.toBeVisible()
    await expect(page.getByLabel('Class name', { exact: true })).toHaveValue(classSection.name)
    expect(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBeLessThanOrEqual(1)
  })
}
